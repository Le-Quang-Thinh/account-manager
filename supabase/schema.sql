-- Chạy 1 lần trong Supabase: SQL Editor -> dán toàn bộ file này -> Run.
-- Truy cập DB chỉ qua server (biến DATABASE_URL, role postgres). RLS bật và không có policy nào,
-- nên anon key / Data API của Supabase không đọc hay ghi được gì.

create table if not exists users (
  id bigint generated by default as identity primary key,
  username text not null,
  pass_hash text not null,
  is_admin boolean not null default false,
  created_at bigint not null
);
create unique index if not exists users_username_key on users (lower(username));

create table if not exists sessions (
  token_hash text primary key,
  user_id bigint not null references users(id) on delete cascade,
  expires_at bigint not null
);
create index if not exists idx_sessions_user on sessions(user_id);

-- Mỗi user một store riêng: id account chỉ duy nhất trong phạm vi user
create table if not exists accounts (
  user_id bigint not null references users(id) on delete cascade,
  id bigint not null,
  raw text not null,
  acc_user text not null,
  batch integer not null,
  status text not null,
  in_list boolean not null default true,
  note text not null default '',
  sale text not null default '',
  sold_at bigint,
  prev text not null default 'special',
  added_at bigint not null default 0,
  primary key (user_id, id)
);
create index if not exists idx_accounts_user on accounts(user_id, lower(acc_user));
create index if not exists idx_accounts_status on accounts(user_id, status);

-- settings, seq, batchSeq, batchMeta, tags... của từng user (JSON dạng text)
create table if not exists user_meta (
  user_id bigint primary key references users(id) on delete cascade,
  value text not null
);

-- Quản lý Green Raid: rev tăng mỗi lần ghi để phát hiện sửa từ máy khác
create table if not exists greenraid_batches (
  user_id bigint not null references users(id) on delete cascade,
  id text not null,
  pos integer not null,
  name text not null,
  file_name text not null,
  primary key (user_id, id)
);
create table if not exists greenraid_accounts (
  user_id bigint not null references users(id) on delete cascade,
  id text not null,
  batch_id text not null,
  pos integer not null,
  text text not null,
  checked boolean not null default false,
  fail_label text not null default '',
  special boolean not null default false,
  exported boolean not null default false,
  export_batch_id text not null default '',
  primary key (user_id, id)
);
create index if not exists idx_greenraid_accounts_batch on greenraid_accounts(user_id, batch_id, pos);
create table if not exists greenraid_history (
  user_id bigint not null references users(id) on delete cascade,
  id text not null,
  pos integer not null,
  name text not null,
  count integer not null,
  created_at bigint not null,
  primary key (user_id, id)
);
create table if not exists greenraid_meta (
  user_id bigint primary key references users(id) on delete cascade,
  rev bigint not null,
  updated_at bigint not null
);

-- Telegram: chat đã liên kết và user đang được chọn của chat đó
create table if not exists telegram_links (
  chat_id bigint primary key,
  user_id bigint references users(id) on delete set null,
  linked_at bigint not null
);
create index if not exists idx_telegram_user on telegram_links(user_id);

-- Chống dò mật khẩu (đăng nhập, /link): serverless không giữ được bộ nhớ giữa các lần gọi nên lưu ở DB
create table if not exists login_fails (
  key text primary key,
  n integer not null,
  locked_until bigint not null
);

